struct Segment { std::uint32_t start; std::uint64_t base; unsigned shift; };
template<std::size_t N> Grid expand(const char* name, const Segment (&segments)[N]) {
    Grid grid; grid.name=name; grid.ticks.resize(65536);
    std::size_t segment=0;
    for (unsigned code=0; code<65536; ++code) {
        while (segment+1<N && segments[segment+1].start<=code) ++segment;
        const auto& item=segments[segment];
        grid.ticks[code]=item.base+(std::uint64_t(code-item.start)<<item.shift);
    }
    return grid;
}
